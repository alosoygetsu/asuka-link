"""Bakes the launcher's font at its crisp size into launcher/font_data.inc.

Since v1.3.0 it is Silkscreen (Jason Kottke, SIL Open Font License 1.1), in launcher/fonts/ with its licence:
    python tools/bake_launcher_font.py
Before, Feerdus's port used Pixel Digivolve (Pixel Sagas), size 10 with M, N and W redrawn: pass its .otf to bake it
again (its licence doesn't allow it in the repo): python tools/bake_launcher_font.py "Pixel Digivolve.otf"
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

SILKSCREEN = Path(__file__).resolve().parents[1] / "launcher/fonts/Silkscreen-Regular.ttf"
CELL_W = 16
CELL_H = 18
BASELINE = 13
CHARS = [*range(32, 127), *range(161, 256), 0x152, 0x153]
OUT = Path(__file__).resolve().parents[1] / "launcher/font_data.inc"
# Pixel Digivolve's M, N and W come out mangled at size 10 (W reads as H): redrawn by hand, accents kept.
DIGIVOLVE_FIXED = {
    "M": ["##...##", "###.###", "#######", "##.#.##", "##...##", "##...##", "##...##"],
    "N": ["##..##", "###.##", "###.##", "######", "##.###", "##.###", "##..##"],
    "W": ["##...##", "##...##", "##...##", "##.#.##", "#######", "###.###", "##...##"],
}
DIGIVOLVE_FIXED.update({k: DIGIVOLVE_FIXED[v] for k, v in {"m": "M", "n": "N", "w": "W", "Ñ": "N", "ñ": "N"}.items()})


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else SILKSCREEN
    digivolve = path != SILKSCREEN
    size, fixed, name = (10, DIGIVOLVE_FIXED, "Pixel Digivolve (Pixel Sagas, Neale Davidson)") if digivolve else (8, {}, "Silkscreen (Jason Kottke, OFL)")
    font = ImageFont.truetype(str(path), size)
    glyphs = []
    for cp in CHARS:
        im = Image.new("1", (CELL_W, CELL_H), 0)
        draw = ImageDraw.Draw(im)
        draw.fontmode = "1"
        draw.text((0, BASELINE), chr(cp), font=font, fill=1, anchor="ls")
        rows = [sum(1 << x for x in range(CELL_W) if im.getpixel((x, y))) for y in range(CELL_H)]
        for i, row in enumerate(fixed.get(chr(cp), [])):
            rows[BASELINE - 7 + i] = sum(1 << x for x, c in enumerate(row) if c == "#")
        glyphs.append((cp, round(font.getlength(chr(cp))), rows))
    top = min(y for _, _, rows in glyphs for y in range(CELL_H) if rows[y])
    bottom = max(y for _, _, rows in glyphs for y in range(CELL_H) if rows[y])
    lines = [
        f"/* Generated by tools/bake_launcher_font.py from {name}. */",
        f"#define FONT_H {bottom - top + 1}",
        f"#define FONT_CAP_TOP {BASELINE - round(font.getbbox('H', anchor='ls')[3] - font.getbbox('H', anchor='ls')[1]) - top}",
        "static const struct { Uint16 cp; Uint8 advance; Uint16 rows[FONT_H]; } FONT[] = {",
    ]
    for cp, advance, rows in glyphs:
        lines.append(f"    {{{cp}, {advance}, {{{', '.join(str(r) for r in rows[top:bottom + 1])}}}}},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"{OUT}: {len(glyphs)} glyphs, {bottom - top + 1} rows, widest {max(a for _, a, _ in glyphs)}")


if __name__ == "__main__":
    main()
