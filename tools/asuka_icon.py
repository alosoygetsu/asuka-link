"""Asuka Link's icon (v1.3.0): "AL" in pixel letters, the A in the link's cyan and the L in signal yellow, with the
signal's waves top right, on the launcher's ink blue with a thick edge. Drawn here pixel by pixel at 32 and at 16 px
(the waves redrawn by hand for each), and from them:
- platform/dw3.ico, the game's and the launcher's (16 and 32 as drawn, 48 the 16 x3, 64-256 the 32 x2-x8);
- launcher/icon_data.inc, the 32 for the launcher's menu (icon.c art_icon).
Run: python tools/asuka_icon.py"""
import io
import struct
from pathlib import Path
from PIL import Image

NATIVE = Path(__file__).resolve().parents[1]
# e the edge, . the ink, c cyan, y yellow, " " clear (the corners)
COLOURS = {"e": 0x1F5F6E, ".": 0x04111B, "c": 0x5CE6FF, "y": 0xFFE08A}


def make(n, edge, a, l, ax, lx, ly, waves, wx, wy):
    g = [["e" if min(x, y, n - 1 - x, n - 1 - y) < edge else "." for x in range(n)] for y in range(n)]
    for x, y in ((0, 0), (n - 1, 0), (0, n - 1), (n - 1, n - 1)):
        g[y][x] = " "
    for art, ox, oy in ((a, ax, ly), (l, lx, ly), (waves, wx, wy)):
        for r, row in enumerate(art):
            for k, v in enumerate(row):
                if v != ".":
                    g[oy + r][ox + k] = v
    return ["".join(r) for r in g]


A32 = ["..ccccccc..", ".ccccccccc."] + ["ccc.....ccc"] * 5 + ["ccccccccccc"] * 2 + ["ccc.....ccc"] * 8
L32 = ["yyy......"] * 14 + ["yyyyyyyyy"] * 3
WAVES32 = ["ccccc....", "cccccc...", ".....cc..", "......cc.", "ccc....cc", "cccc...cc", "...cc..cc", "yy.cc..cc", "yy.cc..cc"]
A16 = [".ccc.", "cc.cc", "cc.cc", "ccccc", "cc.cc", "cc.cc", "cc.cc"]
L16 = ["yy..", "yy..", "yy..", "yy..", "yy..", "yyyy", "yyyy"]
WAVES16 = ["ccc..", "...c.", "cc..c", "..c.c", "y.c.c"]
ICON32 = make(32, 2, A32, L32, 4, 16, 12, WAVES32, 20, 3)
ICON16 = make(16, 1, A16, L16, 2, 8, 7, WAVES16, 10, 1)


def image(rows):
    im = Image.new("RGBA", (len(rows), len(rows)))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            c = COLOURS.get(ch)
            im.putpixel((x, y), (c >> 16, c >> 8 & 255, c & 255, 255) if c is not None else (0, 0, 0, 0))
    return im


def main():
    big, small = image(ICON32), image(ICON16)
    sizes = [(16, small), (32, big), (48, small.resize((48, 48), Image.NEAREST))]
    sizes += [(n, big.resize((n, n), Image.NEAREST)) for n in (64, 128, 256)]
    entries = []
    for n, im in sizes:
        buf = io.BytesIO()
        im.save(buf, "PNG")
        entries.append((n, buf.getvalue()))
    out = struct.pack("<HHH", 0, 1, len(entries))
    offset = 6 + 16 * len(entries)
    for n, png in entries:
        out += struct.pack("<BBBBHHII", n % 256, n % 256, 0, 0, 1, 32, len(png), offset)
        offset += len(png)
    (NATIVE / "platform/dw3.ico").write_bytes(out + b"".join(png for _, png in entries))
    lines = ["/* Generated by tools/asuka_icon.py: do not edit. Asuka Link's icon, 32 x 32: e edge, . ink, c cyan, y yellow, space clear */",
             "static const char *const ICON[32] = {"] + [f'    "{r}",' for r in ICON32] + ["};", ""]
    (NATIVE / "launcher/icon_data.inc").write_text("\n".join(lines), encoding="ascii", newline="\n")
    print("platform/dw3.ico", [n for n, _ in entries], "and launcher/icon_data.inc")


if __name__ == "__main__":
    main()
