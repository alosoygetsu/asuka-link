"""The extra starter packs' texts (tools/packs_text/<language>.toml) in the
game's text encoding, into platform/packs_text.h: one text file each, as the
game's (a count, each string's offset, the strings). Encoded by ddw3's
mklang-file (https://github.com/markisha64/ddw3), passed as its path:

    python native/tools/packs_text.py path/to/mklang-file.exe

Without mklang-file, --sin-mklang changes only the strings that differ from the
last commit's .toml files: it encodes them with tools/game_text.py, and keeps
every other string's bytes as the committed platform/packs_text.h has them.
A changed or new string with a code ("[name]", "[pause]"...) still needs
mklang-file, since a code's bytes aren't known here:

    python native/tools/packs_text.py --sin-mklang

Index: 0 "", 1-3 the packs' names, 4-6 the labels D E F, 7-9 the packs'
texts, 10 Veemon's text, 11 Veemon's greeting in the lobby, 12-13 the word
of the intro's text and the one that replaces it ("three", "six").
And the port's other texts: 14 fast travel's question, 15 DIGILOG's name (the
journal), 16-17 its tabs (active, done), 18-109 each story step's title and
text (GAME.progress 0 to 0x2D), 110-112 the bar's kinds (main, side, done),
then from 113 each side quest's text (ststatus/item_list.c's SIDE_QUESTS).
"""
import subprocess
import sys
import tempfile
from pathlib import Path

NATIVE = Path(__file__).resolve().parents[1]
LANGUAGES = ["eng", "fra", "ita", "ger", "spn"]


def git_show(path):
    """a file of native/ as the last commit has it"""
    return subprocess.run(["git", "show", f"HEAD:{path}"], cwd=NATIVE, check=True, capture_output=True).stdout.decode("utf-8")


def toml_strings(text):
    import tomllib
    return tomllib.loads(text)["strings"]


def without_mklang():
    """platform/packs_text.h from the committed one: the strings that changed since the last commit encoded here, the
    others' bytes kept (see the docstring)"""
    sys.path.insert(0, str(NATIVE / "tools"))
    import game_text
    old_h = git_show("platform/packs_text.h")
    old = {lang: toml_strings(git_show(f"tools/packs_text/{lang}.toml")) for lang in LANGUAGES}
    table = game_text.learn(old_h, old)
    out = ["/* Generated by tools/packs_text.py from tools/packs_text/<language>.toml: do not edit */", ""]
    bad, changed = [], 0
    for lang in LANGUAGES:
        # read as bytes: Path.read_text would turn the .toml's CRLF into LF, which tomllib doesn't mind either way
        new = toml_strings((NATIVE / "tools/packs_text" / f"{lang}.toml").read_bytes().decode("utf-8"))
        b = game_text._packs_file(old_h, lang)
        n = int.from_bytes(b[:4], "little")
        offs = [int.from_bytes(b[4 + 4 * i:8 + 4 * i], "little") for i in range(n)]
        ends = offs[1:] + [len(b)]
        parts = []
        for k, s in enumerate(new):
            if k < n and k < len(old[lang]) and s == old[lang][k]:
                parts.append(b[offs[k]:ends[k]])  # as it was, its padding included
            elif "[" in s:
                bad.append(f"{lang} #{k}: {s!r}")
                parts.append(b"")
            else:
                e = game_text.encode(table, s)
                parts.append(e + bytes(-len(e) % 4))
                changed += 1
        head = 4 + 4 * len(parts)
        pos, offsets = head, []
        for part in parts:
            offsets.append(pos)
            pos += len(part)
        data = len(parts).to_bytes(4, "little") + b"".join(o.to_bytes(4, "little") for o in offsets) + b"".join(parts)
        data += bytes(-len(data) % 4)
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        out.append(f"static const uint32_t PACKS_TEXT_{lang.upper()}[] = {{")
        out += ["    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 6]) + "," for i in range(0, len(words), 6)]
        out += ["};", ""]
    if bad:
        sys.exit("these need mklang-file (they have codes and changed):\n  " + "\n  ".join(bad))
    (NATIVE / "platform/packs_text.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
    game_text.learn()  # every string, the new ones too, is what its bytes say
    print(f"platform/packs_text.h: {changed} strings encoded here, the rest kept")


def main():
    if sys.argv[1:] == ["--sin-mklang"]:
        return without_mklang()
    out =["/* Generated by tools/packs_text.py from tools/packs_text/<language>.toml: do not edit */", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for lang in LANGUAGES:
            src, dst = NATIVE / "tools/packs_text" / f"{lang}.toml", Path(tmp) / f"{lang}.bin"
            subprocess.run([sys.argv[1], str(src), "--output", str(dst)], check=True)
            b = dst.read_bytes()
            b += bytes(-len(b) % 4)
            words = [int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]
            out.append(f"static const uint32_t PACKS_TEXT_{lang.upper()}[] = {{")
            out += ["    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 6]) + "," for i in range(0, len(words), 6)]
            out += ["};", ""]
    (NATIVE / "platform/packs_text.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("platform/packs_text.h")


if __name__ == "__main__":
    main()
